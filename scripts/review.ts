import {chromium} from '@playwright/test';
import {readdir,writeFile} from 'node:fs/promises';
const cache='/Users/anicolao/Library/Caches/ms-playwright';
const available=(await readdir(cache)).filter(f=>/^chromium-\d+$/.test(f)).sort((a,b)=>Number(b.split('-')[1])-Number(a.split('-')[1]));
const browser=await chromium.launch({headless:true,executablePath:`${cache}/${available[0]}/chrome-mac-arm64/Google Chrome for Testing.app/Contents/MacOS/Google Chrome for Testing`});
const page=await browser.newPage({viewport:{width:1440,height:1100},deviceScaleFactor:1});
const errors:string[]=[];
page.on('pageerror',e=>errors.push(e.message));
await page.goto('http://127.0.0.1:5197/gallery');
await page.evaluate(()=>document.querySelectorAll('img').forEach(i=>i.loading='eager'));
await page.evaluate(()=>document.fonts.ready);
await page.waitForFunction(()=>Array.from(document.images).every(i=>i.complete));
const broken=await page.evaluate(()=>Array.from(document.images).filter(i=>!i.naturalWidth).map(i=>i.src));
const overflow=await page.locator('[data-fit]').evaluateAll(nodes=>nodes.filter(n=>n.scrollHeight>n.clientHeight+2||n.scrollWidth>n.clientWidth+2).map(n=>({card:n.closest('[data-card-id]')?.getAttribute('data-card-id'),region:n.getAttribute('data-fit'),scroll:n.scrollHeight,height:n.clientHeight})));
await page.screenshot({path:'tmp/qa/gallery-desktop.png',fullPage:false});
await page.getByRole('button',{name:'Inspect Amdusias',exact:true}).click();
await page.getByRole('dialog').waitFor({state:'visible'});
await page.screenshot({path:'tmp/qa/card-inspector.png'});
await page.keyboard.press('Escape');
await page.getByRole('button',{name:/Minor Arcana/}).click();
const minorCount=await page.locator('.gallery-item').count();
await page.locator('.gallery-toolbar select').selectOption('Cups');
const cupsCount=await page.locator('.gallery-item').count();
await page.setViewportSize({width:390,height:844});
await page.screenshot({path:'tmp/qa/gallery-mobile.png',fullPage:false});
const galleryHorizontalOverflow=await page.evaluate(()=>document.documentElement.scrollWidth>innerWidth);
await page.goto('http://127.0.0.1:5197/rules.html');
await page.evaluate(()=>document.fonts.ready);
await page.screenshot({path:'tmp/qa/rules-mobile.png',fullPage:false});
const rulesHorizontalOverflow=await page.evaluate(()=>document.documentElement.scrollWidth>innerWidth);
await page.setViewportSize({width:1440,height:1100});
await page.screenshot({path:'tmp/qa/rules-desktop.png',fullPage:false});
const referenceSections=await page.locator('.reference-entry').count();
const interactiveControls=await page.locator('.rulebook-document button,.rulebook-document input,.rulebook-document select').count();
const illustratedTricks=await page.locator('.static-trick').count();
await page.evaluate(()=>document.querySelectorAll('img').forEach(i=>i.loading='eager'));
await page.waitForFunction(()=>Array.from(document.images).every(i=>i.complete));
await page.emulateMedia({media:'print'});
await page.evaluate(()=>new Promise<void>(resolve=>requestAnimationFrame(()=>requestAnimationFrame(()=>resolve()))));
await page.pdf({path:'static/downloads/hells-bells-rulebook.pdf',format:'A4',printBackground:true,preferCSSPageSize:true,displayHeaderFooter:false});
const report={errors,broken,overflow,minorCount,cupsCount,galleryHorizontalOverflow,rulesHorizontalOverflow,referenceSections,interactiveControls,illustratedTricks};
await writeFile('tmp/qa/report.json',JSON.stringify(report,null,2));
console.log(JSON.stringify(report,null,2));
await browser.close();
if(errors.length||broken.length||overflow.length||minorCount!==56||cupsCount!==14||galleryHorizontalOverflow||rulesHorizontalOverflow||!referenceSections||interactiveControls||illustratedTricks!==3)process.exit(1);
